-- Тест 3: SELECT с GROUP BY и HAVING
DECLARE
    TYPE dept_rec IS RECORD (
        department      departments.name%TYPE,
        employee_count  NUMBER
    );
    l_cursor  SYS_REFCURSOR;
    l_dept    dept_rec;
BEGIN
    l_cursor := execute_select('{
        "type": "SELECT",
        "columns": ["departments.name AS department", "COUNT(employees.id) AS employee_count"],
        "tables": ["departments"],
        "joins": [{
            "type": "LEFT",
            "table": "employees",
            "on": "employees.department_id = departments.id"
        }],
        "group_by": ["departments.name"],
        "having": "COUNT(employees.id) > 1"
    }');
    LOOP
        FETCH l_cursor INTO l_dept.department, l_dept.employee_count;
        EXIT WHEN l_cursor%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('--------------------------------');
        DBMS_OUTPUT.PUT_LINE('Department: ' || l_dept.department || ', Employee Count: ' || l_dept.employee_count);
    END LOOP;
    CLOSE l_cursor;
END;
