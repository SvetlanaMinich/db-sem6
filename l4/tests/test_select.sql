-- Тест 1: SELECT — простой пример
DECLARE
    TYPE emp_rec IS RECORD (
        id employees.id%TYPE,
        name employees.name%TYPE,
        age employees.age%TYPE,
        department departments.name%TYPE
    );
    l_cursor SYS_REFCURSOR;
    l_emp emp_rec;
BEGIN
    l_cursor := execute_select('{
        "type": "SELECT",
        "columns": ["employees.id", "employees.name", "employees.age", "departments.name AS department"],
        "tables": ["employees"],
        "joins": [{
            "type": "INNER",
            "table": "departments",
            "on": "employees.department_id = departments.id"
        }]
    }');
    LOOP
        FETCH l_cursor INTO l_emp.id, l_emp.name, l_emp.age, l_emp.department;
        EXIT WHEN l_cursor%NOTFOUND;
        DBMS_OUTPUT.PUT_LINE('--------------------------------');
        DBMS_OUTPUT.PUT_LINE('ID: ' || l_emp.id || ', Name: ' || l_emp.name || ', Age: ' || l_emp.age || ', Department: ' || l_emp.department);
    END LOOP;
    CLOSE l_cursor;
END;
